def test_sqlite_schema_drift_fails_before_v006_marker(tmp_path):
    path = tmp_path / "drift.db"
    connection = sqlite3.connect(path)
    _base_schema(connection)
    connection.execute("CREATE TABLE transport_events (id TEXT PRIMARY KEY, freight_order_id TEXT)")
    connection.execute("CREATE TABLE schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)")
    connection.commit()
    with pytest.raises(RuntimeError, match="transport_events schema mismatch"):
        v006_tms_execution_events.upgrade_sqlite(connection)
    assert connection.execute(
        "SELECT 1 FROM schema_migrations WHERE version=?", (v006_tms_execution_events.VERSION,)
    ).fetchone() is None
    connection.close()


def test_postgresql_validation_failure_happens_before_v006_marker():
    class Connection:
        def __init__(self): self.sql = []
        def execute(self, statement, params=None):
            sql = str(statement); self.sql.append(sql)
            if sql.startswith("SELECT version"): return []
            if "information_schema.columns" in sql: return []
            return []
    class Begin:
        def __init__(self, connection): self.connection = connection
        def __enter__(self): return self.connection
        def __exit__(self, *_): return False
    class Engine:
        def __init__(self): self.connection = Connection()
        def begin(self): return Begin(self.connection)
    engine = Engine()
    with pytest.raises(RuntimeError, match="transport_events schema mismatch"):
        upgrade("postgresql://not-connected/epl", engine=engine)
    assert not any(
        sql.startswith("INSERT INTO schema_migrations") and "version" in sql
        for sql in engine.connection.sql[engine.connection.sql.index(next(s for s in engine.connection.sql if "transport_events" in s)):]
    )


def _drifted_v006(connection, old, new):
    _base_schema(connection)
    for sql in v006_tms_execution_events.statements("sqlite"):
        sqlite_sql = sql.replace("INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY", "INTEGER PRIMARY KEY AUTOINCREMENT")
        connection.execute(sqlite_sql.replace(old, new))


