def _base_schema(connection):
    connection.executescript("""
        PRAGMA foreign_keys=ON;
        CREATE TABLE freight_orders (id TEXT PRIMARY KEY);
        CREATE TABLE delivery_orders (id TEXT PRIMARY KEY);
        INSERT INTO freight_orders(id) VALUES ('FO-1'), ('FO-2');
        INSERT INTO delivery_orders(id) VALUES ('DO-1'), ('DO-2');
    """)


def test_v006_sqlite_schema_matches_execution_models(tmp_path):
    connection = sqlite3.connect(tmp_path / "v006.db")
    _base_schema(connection)
    v006_tms_execution_events.upgrade_sqlite(connection)

    tables = {row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    assert {"transport_events", "transport_event_documents", "freight_order_legacy_links"} <= tables
    event_columns = {row[1] for row in connection.execute('PRAGMA table_info("transport_events")')}
    assert {"eta", "payload_hash", "idempotency_key", "recorded_at", "recorded_by"} <= event_columns
    document_columns = {row[1] for row in connection.execute('PRAGMA table_info("transport_event_documents")')}
    assert {"document_type", "storage_url", "file_name", "mime_type", "checksum", "uploaded_at", "uploaded_by"} <= document_columns

    foreign_keys = {
        (table, row[2], row[3])
        for table in ("transport_events", "transport_event_documents", "freight_order_legacy_links")
        for row in connection.execute(f'PRAGMA foreign_key_list("{table}")')
    }
    assert ("transport_events", "freight_orders", "freight_order_id") in foreign_keys
    assert ("transport_event_documents", "transport_events", "event_id") in foreign_keys
    assert ("freight_order_legacy_links", "delivery_orders", "delivery_order_id") in foreign_keys

    indexes = {row[1]: row[2] for row in connection.execute('PRAGMA index_list("transport_events")')}
    assert indexes["ix_transport_events_order_time"] == 0
    assert indexes["sqlite_autoindex_transport_events_2"] == 1
    index_columns = [row[2] for row in connection.execute('PRAGMA index_info("ix_transport_events_order_time")')]
    assert index_columns == ["freight_order_id", "event_time", "recorded_at"]
    connection.close()


def test_v006_sqlite_upgrade_is_idempotent_and_constraints_are_enforced(tmp_path):
    connection = sqlite3.connect(tmp_path / "constraints.db")
    _base_schema(connection)
    v006_tms_execution_events.upgrade_sqlite(connection)
    v006_tms_execution_events.upgrade_sqlite(connection)
    event = ("EV-1", "FO-1", "check_in", "2026-08-11 07:55:00", 10.8, 106.6, 0, 0,
             "device", "GPS-1", "key-1", "hash-1", "dispatcher")
    connection.execute("""
        INSERT INTO transport_events
          (id, freight_order_id, event_type, event_time, lat, lng, speed_kmh, distance_km,
           source, device_id, idempotency_key, payload_hash, recorded_by)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, event)
    with pytest.raises(sqlite3.IntegrityError):
        connection.execute("""
            INSERT INTO transport_events
              (id, freight_order_id, event_type, event_time, source, idempotency_key, payload_hash, recorded_by)
            VALUES ('EV-2','FO-1','pickup','2026-08-11 08:00:00','manual','key-1','hash-2','dispatcher')
        """)
    connection.execute("INSERT INTO freight_order_legacy_links VALUES ('FO-1','DO-1')")
    with pytest.raises(sqlite3.IntegrityError):
        connection.execute("INSERT INTO freight_order_legacy_links VALUES ('FO-2','DO-1')")
    defaults = {"event_type": "check_in", "source": "manual", "lat": 10, "lng": 106,
                "speed_kmh": 0, "distance_km": 0}
    for column, value in (("event_type", "unknown"), ("source", "satellite"), ("lat", 91),
                          ("lng", 181), ("speed_kmh", -1), ("distance_km", -1)):
        invalid = defaults | {column: value}
        with pytest.raises(sqlite3.IntegrityError):
            connection.execute("""
                INSERT INTO transport_events
                  (id, freight_order_id, event_type, event_time, source, idempotency_key,
                   payload_hash, recorded_by, lat, lng, speed_kmh, distance_km)
                VALUES (?, 'FO-2', ?, '2026-08-11', ?, ?, 'hash', 'actor', ?, ?, ?, ?)
            """, (f"BAD-{column}", invalid["event_type"], invalid["source"], f"key-{column}",
                  invalid["lat"], invalid["lng"], invalid["speed_kmh"], invalid["distance_km"]))
    connection.close()


